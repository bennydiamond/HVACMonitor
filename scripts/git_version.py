#!/usr/bin/env python3
# Writes include/GitVersion.h with the suffix appended to the firmware version:
# "-<short git hash>", followed by '+' when tracked files have uncommitted changes.
# A clean build of a tagged commit is a release and gets no suffix. The header is only
# rewritten when its content changes, so only FirmwareVersion.cpp is recompiled.
import os
import subprocess


def git(project_dir, *args):
    return subprocess.run(["git", *args], cwd=project_dir, capture_output=True,
                          text=True, check=True).stdout.strip()


def is_tagged(project_dir):
    try:
        git(project_dir, "describe", "--exact-match", "--tags", "HEAD")
        return True
    except subprocess.CalledProcessError:
        return False


def version_suffix(project_dir):
    try:
        short = git(project_dir, "rev-parse", "--short=7", "HEAD")
        # Untracked files (e.g. a built bootloader hex in the urboot submodule) don't count
        dirty = git(project_dir, "status", "--porcelain", "--untracked-files=no",
                    "--ignore-submodules=untracked")
        if not dirty and is_tagged(project_dir):
            return ""
        return "-" + short + ("+" if dirty else "")
    except (OSError, subprocess.CalledProcessError):
        return "-unknown"


def write_header(project_dir):
    header = os.path.join(project_dir, "include", "GitVersion.h")
    content = (
        "// Generated by scripts/git_version.py at build time: do not edit or commit\n"
        "#pragma once\n\n"
        f"#define HVACMONITOR_VERSION_SUFFIX \"{version_suffix(project_dir)}\"\n"
    )
    try:
        with open(header, "r", encoding="utf-8") as f:
            if f.read() == content:
                return
    except OSError:
        pass
    with open(header, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[git_version] {content.splitlines()[-1]}")


if __name__ == "__main__":
    import sys
    target_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.abspath(
        os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    write_header(target_dir)
else:
    # PlatformIO SCons execution: __file__ is not defined there, use the project dir from env
    Import("env")
    write_header(env.subst("$PROJECT_DIR"))
