#!/usr/bin/env python3
import os
import gzip
import hashlib

def format_hex_array(data: bytes, bytes_per_line: int = 16) -> str:
    lines = []
    for i in range(0, len(data), bytes_per_line):
        chunk = data[i:i + bytes_per_line]
        hex_vals = [f"0x{b:02X}" for b in chunk]
        lines.append("    " + ", ".join(hex_vals))
    return ",\n".join(lines)

def build_assets():
    # Resolve project root (directory containing platformio.ini)
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_dir = os.path.abspath(os.path.join(script_dir, ".."))
    
    web_dir = os.path.join(project_dir, "web")
    output_header = os.path.join(project_dir, "include", "webserver", "WebServerAssetsGz.h")
    
    css_path = os.path.join(web_dir, "style.css")
    js_path = os.path.join(web_dir, "app.js")
    
    if not os.path.exists(css_path) or not os.path.exists(js_path):
        print(f"[compress_web_assets] Warning: source web assets missing in {web_dir}")
        return

    with open(css_path, "rb") as f:
        css_data = f.read()
    with open(js_path, "rb") as f:
        js_data = f.read()

    # Calculate content hash to check if regeneration is needed
    hasher = hashlib.sha256()
    hasher.update(css_data)
    hasher.update(js_data)
    content_hash = hasher.hexdigest()

    # Check if target already exists and is up to date
    if os.path.exists(output_header):
        with open(output_header, "r", encoding="utf-8") as f:
            header_content = f.read()
            if f"// SHA256: {content_hash}" in header_content:
                # Up to date, no rewrite needed
                return

    # Compress assets (level 9, mtime=0 for deterministic output)
    css_gz = gzip.compress(css_data, compresslevel=9, mtime=0)
    js_gz = gzip.compress(js_data, compresslevel=9, mtime=0)

    css_array_str = format_hex_array(css_gz)
    js_array_str = format_hex_array(js_gz)

    os.makedirs(os.path.dirname(output_header), exist_ok=True)
    with open(output_header, "w", encoding="utf-8") as f:
        f.write("#pragma once\n")
        f.write("#include <Arduino.h>\n\n")
        f.write("// Automatically generated by scripts/compress_web_assets.py - DO NOT EDIT MANUALLY\n")
        f.write(f"// SHA256: {content_hash}\n\n")
        f.write(f"// Raw: {len(css_data)} bytes -> Gzip: {len(css_gz)} bytes ({len(css_gz)/len(css_data)*100:.1f}%)\n")
        f.write(f"const uint8_t style_css_gz[{len(css_gz)}] PROGMEM = {{\n")
        f.write(css_array_str)
        f.write("\n};\n")
        f.write(f"const size_t style_css_gz_len = {len(css_gz)};\n\n")
        f.write(f"// Raw: {len(js_data)} bytes -> Gzip: {len(js_gz)} bytes ({len(js_gz)/len(js_data)*100:.1f}%)\n")
        f.write(f"const uint8_t app_js_gz[{len(js_gz)}] PROGMEM = {{\n")
        f.write(js_array_str)
        f.write("\n};\n")
        f.write(f"const size_t app_js_gz_len = {len(js_gz)};\n")

    print(f"[compress_web_assets] Compressed web/style.css: {len(css_data)} -> {len(css_gz)} bytes")
    print(f"[compress_web_assets] Compressed web/app.js: {len(js_data)} -> {len(js_gz)} bytes")
    print(f"[compress_web_assets] Generated {output_header}")

# Support PlatformIO SCons execution
try:
    Import("env")
    build_assets()
except Exception:
    # Direct Python execution (e.g. python scripts/compress_web_assets.py)
    if __name__ == "__main__":
        build_assets()
